"""Synthetic demo data for CrimeNet AI. F7.

    python seed.py            # seed into empty tables
    python seed.py --reset    # drop, recreate, reseed
    python seed.py --verify   # assert the three scenarios and print their IDs

Deterministic: one seeded Random drives every choice, inserts happen in a fixed
order, and --reset resets the SERIAL sequences, so both machines get identical
ids. --verify prints a content digest so that can be checked with one string
comparison rather than trust.

Two things are deliberately NOT in the digest: bcrypt salts a password hash
differently every run, and created_at is generated by Postgres at insert time.
Neither is data we authored.

NO REAL PERSONAL DATA. Every name, number, plate and case reference below is
invented. Any resemblance to a real person or record is coincidence.

Topology note, because it is the part that is easy to get wrong. Scenario C
needs removing one person to split the largest component roughly in half, which
is only true if nothing else joins the two sides. So the whole population is
partitioned into halves, every background relationship stays inside its half,
and the two halves meet only at the bridge.
"""

