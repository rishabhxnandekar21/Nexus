def load_graph(db) -> nx.Graph:
    g = nx.Graph()
    for eid, etype in db.execute(select(Entity.id, Entity.entity_type)):
        g.add_node(eid, entity_type=etype)
    for src, dst in db.execute(select(Relationship.src_entity_id, Relationship.dst_entity_id)):
        if src != dst:
            g.add_edge(src, dst)
    return g


def content_digest(db) -> str:
    """SHA-256 over the data we authored, in id order.

    Excludes password_hash (bcrypt salts differ per run) and created_at
    (Postgres generates it), neither of which we chose.
    """
    h = hashlib.sha256()
    for name, code in db.execute(select(Agency.name, Agency.code).order_by(Agency.id)):
        h.update(f"A|{name}|{code}\n".encode())
    for username, role, aid in db.execute(select(User.username, User.role, User.agency_id).order_by(User.id)):
        h.update(f"U|{username}|{role}|{aid}\n".encode())
    for row in db.execute(select(Entity.entity_type, Entity.name, Entity.attributes,
                                 Entity.agency_id, Entity.source_ref, Entity.is_shared)
                          .order_by(Entity.id)):
        h.update(("E|" + "|".join([row[0], row[1], json.dumps(row[2], sort_keys=True),
                                   str(row[3]), str(row[4]), str(row[5])]) + "\n").encode())
    for row in db.execute(select(Relationship.src_entity_id, Relationship.dst_entity_id,
                                 Relationship.rel_type, Relationship.confidence,
                                 Relationship.valid_from, Relationship.valid_to,
                                 Relationship.source_case, Relationship.agency_id)
                          .order_by(Relationship.id)):
        h.update(("R|" + "|".join(str(v) for v in row) + "\n").encode())
    return h.hexdigest()


def _by_marker(db, marker: str) -> Entity | None:
    """Fetch a scenario entity by its attributes["scenario"] tag."""
    return db.scalar(select(Entity).where(Entity.attributes["scenario"].astext == marker))


def counts(db) -> dict[str, int]:
    out = {"agencies": db.scalar(select(func.count()).select_from(Agency)),
           "users": db.scalar(select(func.count()).select_from(User)),
           "relationships": db.scalar(select(func.count()).select_from(Relationship))}
    for etype, n in db.execute(select(Entity.entity_type, func.count())
                               .group_by(Entity.entity_type).order_by(Entity.entity_type)):
        out[etype] = n
    out["entities"] = db.scalar(select(func.count()).select_from(Entity))
    return out


def verify(db) -> bool:
    ok = True

    def check(label: str, passed: bool, detail: str = "") -> None:
        nonlocal ok
        ok = ok and passed
        print(f"  {'PASS' if passed else 'FAIL'}  {label}" + (f"  -> {detail}" if detail else ""))

    print("Counts")
    for key, value in counts(db).items():
        print(f"  {key:<16} {value}")

    g = load_graph(db)
    print(f"\nGraph: {g.number_of_nodes()} nodes, {g.number_of_edges()} edges, "
          f"{nx.number_connected_components(g)} components")

    # ---- Scenario A
    print("\nScenario A - crime ring")
    boss = _by_marker(db, "A_center")
    check("central figure exists", boss is not None)
    if boss is not None:
        ring = set(nx.single_source_shortest_path_length(g, boss.id, cutoff=1))
        people = [n for n in ring if g.nodes[n].get("entity_type") == "person"]
        years = sorted({r for (r,) in db.execute(
            select(func.extract("year", Relationship.valid_from))
            .where(Relationship.src_entity_id == boss.id))})
        check("ring has 12+ people around it", len(people) >= 12, f"{len(people)} people")
        check("ring spans multiple entity types",
              len({g.nodes[n].get("entity_type") for n in ring}) >= 3,
              str(sorted({g.nodes[n].get("entity_type") for n in ring})))
        check("ring grows over time", len(years) >= 5, f"years {[int(y) for y in years]}")
        print(f"       ring_center_id = {boss.id}")

    # ---- Scenario B
    print("\nScenario B - duplicate identity")
    a = _by_marker(db, "B_record_a")
    b = _by_marker(db, "B_record_b")
    check("both records exist", a is not None and b is not None)
    if a is not None and b is not None:
        check("different agencies", a.agency_id != b.agency_id)
        check("names differ but are close", a.name != b.name, f"{a.name!r} vs {b.name!r}")
        shared = set(g.neighbors(a.id)) & set(g.neighbors(b.id))
        kinds = sorted({g.nodes[n].get("entity_type") for n in shared})
        check("share a phone and a location", {"phone", "location"} <= set(kinds), str(kinds))
        check("dob within a week",
              abs(date.fromisoformat(a.attributes["dob"]) - date.fromisoformat(b.attributes["dob"])).days <= 7)
        print(f"       duplicate_pair = [{a.id}, {b.id}]  shared = {sorted(shared)}")

    # ---- Scenario C
    print("\nScenario C - bridge node")
    bridge = _by_marker(db, "C_bridge")
    check("bridge exists", bridge is not None)
    if bridge is not None:
        biggest = max(nx.connected_components(g), key=len)
        check("bridge is in the largest component", bridge.id in biggest, f"largest = {len(biggest)}")
        cut = g.copy()
        cut.remove_node(bridge.id)
        pieces = sorted((c for c in nx.connected_components(cut) if c & biggest), key=len, reverse=True)
        check("removal splits it in two", len(pieces) >= 2,
              f"pieces {[len(p) for p in pieces[:4]]}")
        if len(pieces) >= 2:
            big, second = len(pieces[0]), len(pieces[1])
            check("halves are roughly equal", second >= 0.35 * (big + second),
                  f"{big} vs {second} ({second / (big + second):.0%} / {big / (big + second):.0%})")
        print(f"       bridge_id = {bridge.id}")

    print(f"\nContent digest: {content_digest(db)}")
    print("  Both machines must print the same digest. Password hashes and")
    print("  created_at are excluded - bcrypt salts and Postgres clocks differ.")
    return ok


# ---------------------------------------------------------------------- main


def main() -> int:
    ap = argparse.ArgumentParser(description="Seed CrimeNet AI demo data.")
    ap.add_argument("--reset", action="store_true", help="drop, recreate and reseed")
    ap.add_argument("--verify", action="store_true", help="check the three scenarios")
    args = ap.parse_args()

    if args.verify and not args.reset:
        with SessionLocal() as db:
            return 0 if verify(db) else 1

    started = time.perf_counter()
    if args.reset:
        print("dropping and recreating every table")
        Base.metadata.drop_all(bind=engine)
    init_db()

    with SessionLocal() as db:
        if db.scalar(select(func.count()).select_from(Entity)):
            print("Tables already hold data. Use --reset to wipe and reseed.", file=sys.stderr)
            return 1
        print(f"seeding with SEED={SEED}")
        Seeder(db).run()

    with SessionLocal() as db:
        for key, value in counts(db).items():
            print(f"  {key:<16} {value}")
        print(f"done in {time.perf_counter() - started:.1f}s")
        if args.verify:
            print()
            return 0 if verify(db) else 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
