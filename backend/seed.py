    # -------------------------------------------------------- relationships

    def build_background(self, halves: dict) -> None:
        """Edges strictly inside one half. Nothing here may cross."""
        for half, pools in halves.items():
            people = pools["person"]
            # 8 per half are left with no edges at all - the PRD asks for
            # deliberate dead-end nodes so the data does not look manufactured
            core = people[:-8]

            # spanning tree first, so the half is guaranteed to be one component
            for i in range(1, len(core)):
                partner = core[self.rng.randint(0, i - 1)]
                self.link(core[i], partner,
                          self.rng.choice(["co_accused", "family_of", "transacted_with"]),
                          "GJ_POLICE", self.a_date())

            for _ in range(40):
                a, b = self.rng.sample(core, 2)
                self.link(a, b, self.rng.choice(["co_accused", "transacted_with"]),
                          "GJ_POLICE", self.a_date())

            for phone in pools["phone"]:
                self.link(self.rng.choice(core), phone, "owns", "TELECOM",
                          self.a_date(START, date(2024, 1, 1)))
            for i in range(0, len(pools["phone"]) - 1, 2):
                started = self.a_date()
                self.link(pools["phone"][i], pools["phone"][i + 1], "called", "TELECOM",
                          started, started + timedelta(days=self.rng.randint(1, 400)))

            for vehicle in pools["vehicle"]:
                self.link(self.rng.choice(core), vehicle, "owns", "RTO",
                          self.a_date(START, date(2024, 1, 1)))
            for vehicle in pools["vehicle"][:20]:
                self.link(vehicle, self.rng.choice(pools["location"]), "registered_at",
                          "RTO", self.a_date())

            for event in pools["crime_event"]:
                when = date.fromisoformat(event.attributes["occurred_on"])
                for person in self.rng.sample(core, self.rng.randint(1, 2)):
                    self.link(person, event,
                              self.rng.choice(["suspect_in", "suspect_in", "witness_in"]),
                              "GJ_POLICE", when, case=event.attributes["case_number"])
                self.link(event, self.rng.choice(pools["location"]), "present_at",
                          "GJ_POLICE", when, case=event.attributes["case_number"])

            for org in pools["organization"]:
                for person in self.rng.sample(core, self.rng.randint(1, 3)):
                    self.link(person, org, "transacted_with", "GJ_POLICE", self.a_date())

    # ------------------------------------------------------------- scenarios

    def scenario_a_ring(self, halves: dict) -> None:
        """A visible ring of 12 around one central figure, growing 2019 -> 2025.

        Uses entities from all three agencies, and the introduction years are
        staggered so the timeline in F6 has something to replay: 3 nodes in 2019,
        the full ring by 2025.
        """
        pool = halves[0]
        ring = pool["person"][:12]
        boss, members = ring[0], ring[1:]
        # Tag them. The general population's source_ref prefix depends on a random
        # agency draw, so it is not a reliable handle - an explicit marker is.
        boss.attributes = {**boss.attributes, "scenario": "A_center"}
        for member in members:
            member.attributes = {**member.attributes, "scenario": "A_member"}
        years = [2019, 2019, 2020, 2020, 2021, 2021, 2022, 2023, 2023, 2024, 2025]
        for member, year in zip(members, years):
            when = date(year, self.rng.randint(1, 12), self.rng.randint(1, 28))
            self.link(boss, member, "co_accused", "GJ_POLICE", when, confidence=0.9,
                      case=f"FIR/{year}/GJ/{self.rng.randint(1000, 9999):05d}")
        # lieutenants, so it reads as a ring rather than a star
        for i in range(1, 6):
            self.link(members[i], members[i + 1], "co_accused", "GJ_POLICE",
                      date(2022 + (i % 3), self.rng.randint(1, 12), 15), confidence=0.85)
        # telecom and RTO records pull the other two agencies into the ring
        for i, member in enumerate(members[:5]):
            self.link(member, pool["phone"][i], "owns", "TELECOM", date(2020 + i % 4, 6, 1))
        for i, member in enumerate(members[5:9]):
            self.link(member, pool["vehicle"][i], "owns", "RTO", date(2021 + i % 3, 3, 1))
        self.link(boss, pool["phone"][10], "owns", "TELECOM", date(2019, 4, 2))
        self.link(boss, pool["vehicle"][10], "owns", "RTO", date(2019, 7, 9))
        self.scenarios["ring_center_id"] = boss.id
        self.scenarios["ring_member_ids"] = [p.id for p in ring]

    def scenario_b_duplicate(self, halves: dict) -> None:
        """One real person recorded twice, in two agencies, spelled differently.

        Shares a phone and an address with itself, and the DOBs are days apart.
        Those are the signals resolution.py scores in F8; the target is ~0.85.
        Both records sit in the SAME half, or they would form a second bridge
        and break scenario C.
        """
        pool = halves[0]
        born = date(1984, 7, 19)
        line, city, district = self.address()

        police = self.entity("person", "Rakesh Kumarbhai Yadav", "GJ_POLICE",
                             {"dob": born.isoformat(), "gender": "M", "alias": "Rakhu",
                              "address": line, "city": city, "scenario": "B_record_a"},
                             "FIR-PER-20881", shared=True)
        rto = self.entity("person", "Rakesh Kumar Yadhav", "RTO",
                          {"dob": (born + timedelta(days=2)).isoformat(), "gender": "M",
                           "alias": "Rakesh", "address": line, "city": city,
                           "scenario": "B_record_b"},
                          "RTO-OWN-70992", shared=True)
        phone = self.entity("phone", self.phone_number(), "TELECOM",
                            {"carrier": "Jio", "activated": "2020-02-11"},
                            "CDR-88999", shared=True)
        home = self.entity("location", line, "GJ_POLICE",
                           {"city": city, "district": district, "address": line},
                           "LOC-31999", shared=True)
        self.db.flush()

        for record in (police, rto):
            self.link(record, phone, "owns", "TELECOM", date(2020, 2, 11))
            self.link(record, home, "present_at", "GJ_POLICE", date(2020, 3, 1))
        # attach both into the same half so neither is an island
        self.link(police, pool["person"][20], "co_accused", "GJ_POLICE", date(2021, 5, 4))
        self.link(rto, pool["vehicle"][3], "owns", "RTO", date(2022, 8, 17))
        self.scenarios["duplicate_pair"] = [police.id, rto.id]
        self.scenarios["duplicate_shared"] = {"phone_id": phone.id, "location_id": home.id}

    def scenario_c_bridge(self, halves: dict) -> None:
        """The only edge set joining the two halves.

        Shared, so both an investigator and an admin can see the split happen.
        """
        bridge = self.entity("person", "Nitin Ramanbhai Chauhan", "GJ_POLICE",
                             {"dob": "1979-11-03", "gender": "M", "alias": "Nittu",
                              "address": "14, Gohil Estate, Odhav", "city": "Ahmedabad",
                              "scenario": "C_bridge"},
                             "FIR-PER-20999", shared=True)
        self.db.flush()
        for half in (0, 1):
            for person in halves[half]["person"][30:33]:
                self.link(bridge, person, "transacted_with", "GJ_POLICE",
                          date(2021 + half, 4 + half, 12), confidence=0.78)
        self.scenarios["bridge_id"] = bridge.id

    # ------------------------------------------------------------------ run

    def run(self) -> dict:
        self.build_reference_rows()
        halves = self.build_population()
        self.build_background(halves)
        self.scenario_a_ring(halves)
        self.scenario_b_duplicate(halves)
        self.scenario_c_bridge(halves)
        self.db.add_all(self.rels)
        self.db.commit()
        return self.scenarios


